"""
PDF certificate generator using ReportLab.

Generates a professional-looking landscape A4 certificate with:
- Decorative double border and corner accents
- Recipient name, course name, and issue date
- Authorized signature placeholder
"""

import os

from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import A4, landscape
from reportlab.pdfgen import canvas


def generate_certificate_pdf(
    recipient_name: str,
    course_name: str,
    issue_date: str,
    output_path: str,
) -> str:
    """
    Generate a single certificate PDF and save it to *output_path*.

    Returns the absolute path of the generated file.

    Raises:
        OSError – if the output directory cannot be created.
        reportlab errors – if PDF generation fails.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    width, height = landscape(A4)
    c = canvas.Canvas(output_path, pagesize=landscape(A4))

    # ── Background ──────────────────────────────────────────────────────
    c.setFillColor(HexColor("#FFFDF7"))
    c.rect(0, 0, width, height, fill=True, stroke=False)

    # ── Outer border ────────────────────────────────────────────────────
    c.setStrokeColor(HexColor("#1a365d"))
    c.setLineWidth(3)
    c.rect(30, 30, width - 60, height - 60, fill=False, stroke=True)

    # ── Inner border ────────────────────────────────────────────────────
    c.setStrokeColor(HexColor("#C9A84C"))
    c.setLineWidth(1.5)
    c.rect(40, 40, width - 80, height - 80, fill=False, stroke=True)

    # ── Decorative corner accents ───────────────────────────────────────
    _draw_corner_accents(c, width, height)

    # ── Title ───────────────────────────────────────────────────────────
    c.setFillColor(HexColor("#1a365d"))
    c.setFont("Helvetica-Bold", 42)
    c.drawCentredString(width / 2, height - 120, "CERTIFICATE")

    c.setFont("Helvetica", 20)
    c.setFillColor(HexColor("#C9A84C"))
    c.drawCentredString(width / 2, height - 155, "OF COMPLETION")

    # Decorative line
    c.setStrokeColor(HexColor("#C9A84C"))
    c.setLineWidth(1)
    c.line(width / 2 - 120, height - 170, width / 2 + 120, height - 170)

    # ── Body text ───────────────────────────────────────────────────────
    c.setFont("Helvetica", 14)
    c.setFillColor(HexColor("#4a5568"))
    c.drawCentredString(width / 2, height - 210, "This is to certify that")

    # Recipient name (prominent)
    c.setFont("Helvetica-Bold", 32)
    c.setFillColor(HexColor("#1a365d"))
    c.drawCentredString(width / 2, height - 260, recipient_name)

    # Underline beneath name
    name_width = c.stringWidth(recipient_name, "Helvetica-Bold", 32)
    half_line = max(name_width / 2 + 30, 150)
    c.setStrokeColor(HexColor("#C9A84C"))
    c.setLineWidth(0.8)
    c.line(width / 2 - half_line, height - 272, width / 2 + half_line, height - 272)

    c.setFont("Helvetica", 14)
    c.setFillColor(HexColor("#4a5568"))
    c.drawCentredString(width / 2, height - 305, "has successfully completed the course")

    # Course name
    c.setFont("Helvetica-BoldOblique", 22)
    c.setFillColor(HexColor("#2d3748"))
    c.drawCentredString(width / 2, height - 345, course_name)

    # Date
    c.setFont("Helvetica", 12)
    c.setFillColor(HexColor("#718096"))
    c.drawCentredString(width / 2, height - 390, f"Date of Issue: {issue_date}")

    # ── Signature line ──────────────────────────────────────────────────
    sig_y = 90
    c.setStrokeColor(HexColor("#2d3748"))
    c.setLineWidth(0.8)
    c.line(width / 2 - 100, sig_y, width / 2 + 100, sig_y)
    c.setFont("Helvetica", 11)
    c.setFillColor(HexColor("#4a5568"))
    c.drawCentredString(width / 2, sig_y - 18, "Authorized Signature")

    # ── Footer watermark ────────────────────────────────────────────────
    c.setFont("Helvetica", 8)
    c.setFillColor(HexColor("#CBD5E0"))
    c.drawCentredString(
        width / 2, 35, "Certificate generated by Bulk Certificate Generator"
    )

    c.save()
    return os.path.abspath(output_path)


def _draw_corner_accents(c: canvas.Canvas, width: float, height: float) -> None:
    """Draw small L-shaped accents in each corner of the inner border."""
    size = 25
    c.setStrokeColor(HexColor("#C9A84C"))
    c.setLineWidth(2)

    # Top-left
    c.line(45, height - 45, 45 + size, height - 45)
    c.line(45, height - 45, 45, height - 45 - size)

    # Top-right
    c.line(width - 45, height - 45, width - 45 - size, height - 45)
    c.line(width - 45, height - 45, width - 45, height - 45 - size)

    # Bottom-left
    c.line(45, 45, 45 + size, 45)
    c.line(45, 45, 45, 45 + size)

    # Bottom-right
    c.line(width - 45, 45, width - 45 - size, 45)
    c.line(width - 45, 45, width - 45, 45 + size)
